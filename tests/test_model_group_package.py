@pytest.mark.asyncio
async def test_cancel_reaps_real_compiler_before_removing_its_inputs(tmp_path, prepared, monkeypatch):
    store = GroupPackageStore(tmp_path / 'packages')
    row = creation(store, prepared)
    source = json.loads(store.read('source', row['source_sha256']))
    source['files']['group_packager.py'] = 'import time\ntime.sleep(60)\n'
    row['source_sha256'] = store.put('source', encoded(source))
    original, spawned, processes = asyncio.create_subprocess_exec, asyncio.Event(), []

    async def launch(*args, **kwargs):
        child = await original(*args, **kwargs)
        processes.append(child)
        spawned.set()
        return child

    monkeypatch.setattr(asyncio, 'create_subprocess_exec', launch)
    task = asyncio.create_task(store(row, 0))
    try:
        await asyncio.wait_for(spawned.wait(), 2)
    finally:
        task.cancel()
        with pytest.raises(asyncio.CancelledError):
            await task
    assert len(processes) == 1 and processes[0].returncode is not None
    assert not list(store.root.glob('.building-*')) and not list(store.root.glob('artifact-*'))


def test_receipt_is_stable_across_node_metadata_but_pins_files_and_architecture(prepared):
    module = load('group_model')
    record, _ = prepared
    expected = module.descriptor(record)
    changed = deepcopy(record)
    for item in changed['files']:
        item['mtime_ns'] += 1000
    changed['name'], changed['revision'] = 'same-bundle-on-another-node', 'display-only'
    changed['files'].reverse()
    module.check_record(changed, expected)
    for field in ('hash', 'size', 'architecture', 'weights', 'path'):
        changed = deepcopy(record)
        if field == 'hash': changed['files'][0]['sha256'] = 'f'*64
        elif field == 'size': changed['files'][0]['size'] += 1
        elif field == 'architecture': changed['config']['num_hidden_layers'] += 1
        elif field == 'weights': changed['tensor_parallel_weights']['2'] += 1
        elif field == 'path': changed['files'][0]['path'] = '../config.json'
        with pytest.raises(ValueError):
            module.check_record(changed, expected)


def test_node_file_verification_handles_timestamp_rounding_but_rejects_corruption(tmp_path, prepared):
    module = load('group_model')
    record, _ = prepared
    root = tmp_path / 'snapshots' / record['sha256']
    module.check_files(root, record)
    item = next(f for f in record['files'] if f['path'].endswith('.safetensors'))
    path = root / item['path']
    original = path.read_bytes()
    # Image-like metadata drift keeps the exact same verified model bytes.
    os.utime(path, ns=(item['mtime_ns'] + 1000, item['mtime_ns'] + 1000))
    module.check_files(root, record)
    assert item['mtime_ns'] != path.stat().st_mtime_ns
    path.chmod(0o600)
    path.write_bytes(b'x' * len(original))
    with pytest.raises(ValueError, match='content verification'):
        module.check_files(root, record)
    path.unlink(); path.symlink_to(tmp_path / 'blobs' / record['sha256'])
    with pytest.raises((ValueError, OSError)):
        module.check_files(root, record)


def test_store_never_follows_links_or_overwrites_corrupt_cached_bytes(tmp_path):
    store = GroupPackageStore(tmp_path / 'packages')
    sha = store.put('source', b'{"fixture":true}')
    target = store.path('source', sha)
    outside = tmp_path / 'outside'; outside.write_bytes(target.read_bytes())
    target.unlink(); target.symlink_to(outside)
    with pytest.raises((ValueError, OSError)):
        store.read('source', sha)
    with pytest.raises((ValueError, OSError)):
        store.put('source', outside.read_bytes())
    assert outside.read_bytes() == b'{"fixture":true}'
    with pytest.raises(ValueError):
        store.path('source', '../escape')


@pytest.mark.asyncio
async def test_underlay_bound_packages_stage_original_bytes_and_never_rebuild(tmp_path, prepared, monkeypatch):
    from types import SimpleNamespace
    from unittest.mock import AsyncMock
    import base64
    from pantheon.apps.lifecycle import FleetLifecycle, CHUNK_SIZE
    prepared[1]['underlay'] = ['192.168.20.10:18441', '192.168.20.11:18441']
    for member in prepared[1]['members']:
        member['interface'] = 'wg0'
    store = GroupPackageStore(tmp_path / 'packages')
    row = creation(store, prepared)
    for rank in range(2):
        row['artifacts'].append(dict(rank=rank, digest=await store(row, rank)))
    row['phase'] = 'built'
    payload = store.artifact(row['artifacts'][0]['digest'])
    assert json.loads(unpack(payload)['group-plan.json'])['underlay'] == prepared[1]['underlay']
    client = SimpleNamespace(lifecycle=AsyncMock(return_value={}))
    lifecycle = FleetLifecycle(None)
    monkeypatch.setattr(lifecycle, '_client', AsyncMock(return_value=client))
    actual = await store.stage(lifecycle, row, 0)
    sent = [c for c in client.lifecycle.await_args_list if c.args[1] == 'stage']
    assert b''.join(base64.b64decode(c.kwargs['data']) for c in sent) == payload
    assert [c.kwargs['offset'] for c in sent] == list(range(0, len(payload), CHUNK_SIZE))
    assert all(c.args[0] == row['plan']['members'][0]['node_id'] and c.kwargs['digest'] == actual for c in sent)
    assert {c.args[1] for c in client.lifecycle.await_args_list} == {'status', 'stage'}
    client.lifecycle.reset_mock()
    client.lifecycle.return_value = {'installations': {actual: {'state': 'installed'}}}
    assert await store.stage(lifecycle, row, 0) == actual
    assert client.lifecycle.await_count == 1
    store.path('artifact', actual).unlink()
    with pytest.raises(ValueError, match='missing'):
        await store.stage(lifecycle, row, 0)
    assert client.lifecycle.await_count == 1
