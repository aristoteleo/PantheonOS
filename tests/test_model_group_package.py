def creation(store, prepared):
    record, value = prepared
    return dict(protocol=1, owner=value['owner'], group_id=value['group_id'], revision=3,
        plan=value, topology=topology_for(value).document(), source_sha256=store.capture(record),
        phase='building', authority_requested=True, ca_sha256='c'*64,
        authority_closed=False, artifacts=[])


def unpack(payload):
    with tarfile.open(fileobj=io.BytesIO(payload), mode='r:') as archive:
        entries = archive.getmembers()
        assert all(entry.isfile() and entry.mode == 0o400 and entry.mtime == 0 for entry in entries)
        return {entry.name: archive.extractfile(entry).read() for entry in entries}


@pytest.mark.asyncio
async def test_real_snapshot_builds_reproducible_rank_packages_without_weights(tmp_path, prepared):
    store = GroupPackageStore(tmp_path / 'packages')
    row = creation(store, prepared)
    first, second = await asyncio.gather(store(row, 0), store(row, 1))
    assert first != second
    assert await GroupPackageStore(store.root)(row, 0) == first
    payload = store.artifact(first)
    files = unpack(payload)
    manifest = json.loads(files['fleet.json'])
    component = manifest['components'][0]
    assert manifest['requires']['caps'] == ['proc', 'model-group-private-network']
    assert component['group_peer'] and component['group_network'] and component['run_as_owner']
    assert component['resources'] == row['plan']['members'][0]['resources']
    assert component['read_only_mounts']['cache/snapshots/' + row['plan']['model_sha256']] == '/fleet/weights'
    assert manifest['dependencies']['container_engine']['provision'] == 'never'
    assert '@sha256:' in component['image'] and 'hooks' not in manifest
    assert json.loads(files['group-peer.json']) == dict(protocol=1, rank=0,
        topology=row['topology'], ca_sha256=row['ca_sha256'])
    assert json.loads(files['group-plan.json']) == row['plan']
    assert json.loads(files['group-build.json']) == dict(protocol=1, source_sha256=row['source_sha256'], rank=0)
    assert not any(name.endswith(('.safetensors', '.pem', '.key')) for name in files)
    assert 'mtime_ns' not in files['group-model.json'].decode()
    assert len(payload) < 512 << 10
    # Generated bytes use Fleet's real canonical artifact format exactly.
    root = tmp_path / 'unpacked'; root.mkdir()
    for name, data in files.items():
        (root / name).write_bytes(data)
    assert build_artifact(root) == (payload, first)
    assert not list(store.root.glob('.building-*'))
    assert not list(store.root.glob('.writing-*'))
    # Optional receipt consumed by the Go admission boundary test.
    if output := os.environ.get('PANTHEON_GROUP_PACKAGE_OUTPUT'):
        Path(output).write_bytes(payload)


@pytest.mark.asyncio
async def test_saved_source_survives_code_changes_and_missing_input_has_no_fallback(tmp_path, prepared, monkeypatch):
    store = GroupPackageStore(tmp_path / 'packages')
    row = creation(store, prepared)
    sha = await store(row, 0)
    # Reconstruct with no access to current capture code. Build must use only
    # the original saved compiler and programs, not import updated App modules.
    monkeypatch.setattr(GroupPackageStore, 'capture', lambda *args: pytest.fail('current source consulted'))
    assert await GroupPackageStore(store.root)(row, 0) == sha
    source = store.path('source', row['source_sha256'])
    original = source.read_bytes()
    source.chmod(0o600); source.write_bytes(b'{}')
    with pytest.raises(ValueError, match='corrupt'):
        await store(row, 0)
    source.unlink()
    with pytest.raises(ValueError, match='missing'):
        await store(row, 0)
    assert store.put('source', original) == row['source_sha256']
    assert await store(row, 0) == sha


